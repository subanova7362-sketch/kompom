function openArchive(index) {

    if (index < 0 || index >= archive.length) {

        return;

    }

    const item = archive[index];

    alert(

        "🧾 Выписка\n\n" +

        "Файл: " + item.name + "\n" +

        "Дата: " + item.date + "\n" +

        "Количество платежей: " +

        item.payments + "\n" +

        "Общая сумма: " +

        item.total

    );

}
/* ==========================================================
                УДАЛИТЬ ВЫПИСКУ
========================================================== */

function deleteArchive(index) {

    if (index < 0 || index >= archive.length) {

        return;

    }

    const answer = confirm(

        "Удалить выписку из архива?"

    );

    if (!answer) {

        return;

    }

    archive.splice(index, 1);

    updateArchive();

}

/* ==========================================================
                ОЧИСТИТЬ АРХИВ
========================================================== */

function clearArchive() {

    const answer = confirm(

        "Очистить весь архив?"

    );

    if (!answer) {

        return;

    }

    archive = [];

    updateArchive();

}

